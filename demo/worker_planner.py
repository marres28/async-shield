"""Worker 2 (Planner): deterministic LLM mock that turns tickets into tool calls.

Role separation:
- In ``protected`` mode, ``worker_planner`` holds a ``LOW``-integrity signing key
  (e.g. ``planner-v1``) to re-seal derived payloads, plus the ``ingest-v1`` key
  to verify upstream envelopes from ``worker_ingest``. It NEVER holds a ``HIGH`` key.
"""

from __future__ import annotations

import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any

import redis

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from shield import KeyRing, ShieldBroker, StreamEnvelope

_INJECTION_USER_RE = re.compile(r"user\s+([a-zA-Z0-9_-]+)", re.IGNORECASE)
_INJECTION_ROLE_RE = re.compile(r"role\s+([a-zA-Z0-9_-]+)", re.IGNORECASE)


def mock_llm_plan(ticket: dict[str, Any]) -> dict[str, Any]:
    """Deterministic LLM simulator (zero external API keys required)."""
    body = str(ticket.get("body", ""))
    lowered = body.lower()
    user_id = str(ticket.get("user_id", "guest_01"))
    ticket_id = str(ticket.get("ticket_id", "TKT-000"))

    injection_markers = (
        "system override",
        "ignore previous instructions",
        "update_user_role",
        "promote",
        "grant admin",
    )
    if any(marker in lowered for marker in injection_markers):
        user_match = _INJECTION_USER_RE.search(body)
        role_match = _INJECTION_ROLE_RE.search(body)
        target_user = user_match.group(1) if user_match else user_id
        target_role = role_match.group(1) if role_match else "admin"
        return {
            "tool": "update_user_role",
            "ticket_id": ticket_id,
            "user_id": target_user,
            "new_role": target_role,
            "planner_note": "Generated by Planner LLM from ticket content",
        }

    return {
        "tool": "reply_to_ticket",
        "ticket_id": ticket_id,
        "user_id": user_id,
        "message": f"Hello {user_id}, we received ticket {ticket_id}.",
    }


class PlannerWorker:
    """Consumes tickets from Redis Streams and publishes re-sealed planned tool calls."""

    def __init__(
        self,
        client: redis.Redis,
        *,
        mode: str = "protected",
        keyring: KeyRing | None = None,
        signing_kid: str | None = None,
        tickets_stream: str = "stream:tickets",
        actions_stream: str = "stream:actions",
        group: str = "planner-group",
        consumer: str = "planner-1",
    ) -> None:
        self.client = client
        self.mode = mode
        self.tickets_stream = tickets_stream
        self.actions_stream = actions_stream
        self.group = group
        self.consumer = consumer
        self.broker: ShieldBroker | None = None

        if mode == "protected":
            if keyring is None:
                raise ValueError("protected mode requires an explicit KeyRing (fail-closed).")
            self.broker = ShieldBroker(client, keyring=keyring, signing_kid=signing_kid)
            self.broker.ensure_group(self.tickets_stream, self.group)
        else:
            try:
                self.client.xgroup_create(self.tickets_stream, self.group, id="0", mkstream=True)
            except redis.exceptions.ResponseError as exc:
                if "BUSYGROUP" not in str(exc):
                    raise

    def process_once(self, block_ms: int = 500) -> list[tuple[dict[str, Any], StreamEnvelope | None]]:
        """Read and process available ticket messages once."""
        results: list[tuple[dict[str, Any], StreamEnvelope | None]] = []

        if self.mode == "vulnerable":
            entries = self.client.xreadgroup(
                groupname=self.group,
                consumername=self.consumer,
                streams={self.tickets_stream: ">"},
                count=10,
                block=block_ms,
            )
            if not entries:
                return results
            for _, msgs in entries:
                for msg_id, fields in msgs:
                    ticket = json.loads(fields.get("payload", "{}"))
                    plan = mock_llm_plan(ticket)
                    self.client.xadd(self.actions_stream, {"payload": json.dumps(plan)})
                    self.client.xack(self.tickets_stream, self.group, msg_id)
                    results.append((plan, None))
            return results

        assert self.broker is not None
        messages = self.broker.consume(
            self.tickets_stream,
            self.group,
            self.consumer,
            count=10,
            block=block_ms,
        )
        for msg in messages:
            plan = mock_llm_plan(msg.envelope.payload)
            _, derived_env = self.broker.publish_derived(
                self.actions_stream,
                msg.envelope,
                plan,
                target_tool=str(plan.get("tool", "")) or None,
                worker_name="worker-planner",
            )
            self.broker.ack(self.tickets_stream, self.group, msg.message_id)
            results.append((plan, derived_env))

        return results

    def run_forever(self) -> None:
        print(
            f"[PLANNER] Started (mode={self.mode}, "
            f"in={self.tickets_stream} -> out={self.actions_stream})",
            flush=True,
        )
        while True:
            for plan, env in self.process_once(block_ms=1000):
                label = (
                    f"{env.context.integrity.value.upper()} (kid={env.kid})"
                    if env
                    else "NONE (RAW)"
                )
                print(
                    f"[PLANNER] Proposed tool='{plan['tool']}' "
                    f"for user='{plan.get('user_id')}' | propagated_integrity={label}",
                    flush=True,
                )


def main() -> None:
    redis_url = os.getenv("REDIS_URL", "redis://localhost:6379/0")
    mode = os.getenv("SHIELD_MODE", "protected")
    keyring = KeyRing.from_env(role="planner") if mode == "protected" else None

    client = redis.Redis.from_url(redis_url, decode_responses=True)
    for _ in range(20):
        try:
            client.ping()
            break
        except redis.exceptions.ConnectionError:
            time.sleep(0.5)

    worker = PlannerWorker(client, mode=mode, keyring=keyring)
    worker.run_forever()


if __name__ == "__main__":
    main()
